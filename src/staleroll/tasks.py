def _variant_cases(name: str, index: int, visible: object, hidden: object) -> Tuple[object, object]:
    """Create deterministic input variants so 50-100 task runs are not copies."""
    if index < len(_CODE_TASK_TEMPLATES):
        return visible, hidden
    rng = random.Random(7001 + index * 31)
    if name == "mean":
        def values() -> List[int]:
            return [rng.randint(-8, 12) for _ in range(rng.randint(2, 6))]
        visible = [((values(),), {}, 0.0)]
        visible[0] = (visible[0][0], visible[0][1], sum(visible[0][0][0]) / len(visible[0][0][0]))
        hidden_values = [rng.randint(-8, 12) for _ in range(4)]
        hidden = [((hidden_values,), {}, sum(hidden_values) / len(hidden_values))]
    elif name == "clamp":
        low = rng.randint(-5, 2); high = low + rng.randint(3, 10)
        visible = [((rng.randint(low, high), low, high), {}, None)]
        visible[0] = (visible[0][0], {}, max(low, min(high, visible[0][0][0])))
        hidden = [((rng.randint(low - 8, high + 8), low, high), {}, None)]
        hidden[0] = (hidden[0][0], {}, max(low, min(high, hidden[0][0][0])))
    elif name == "dedupe":
        values = [rng.randint(0, 5) for _ in range(7)]
        expected = list(dict.fromkeys(values))
        visible = [((values[:4],), {}, list(dict.fromkeys(values[:4])))]
        hidden = [((values,), {}, expected)]
    elif name == "chunk":
        values = [rng.randint(-5, 9) for _ in range(rng.randint(4, 8))]
        n = rng.randint(2, 4)
        expected = [values[i:i + n] for i in range(0, len(values), n)]
        visible = [((values[: max(1, len(values) - 1)], n), {}, [values[: max(1, len(values) - 1)][i:i + n] for i in range(0, max(1, len(values) - 1), n)])]
        hidden = [((values, n), {}, expected)]
    elif name == "flatten":
        rows = [[rng.randint(0, 9) for _ in range(rng.randint(0, 3))] for _ in range(rng.randint(2, 4))]
        expected = [item for row in rows for item in row]
        visible = [((rows[:2],), {}, [item for row in rows[:2] for item in row])]
        hidden = [((rows,), {}, expected)]
    elif name == "count_words":
        words = ["red", "blue", "red", "green"]
        text = "  ".join(words)
        visible = [(("alpha beta",), {}, 2)]
        hidden = [((text,), {}, len(words))]
    elif name == "safe_get":
        key = rng.randint(1, 9)
        visible = [(({"a": 1}, "a", 0), {}, 1)]
        hidden = [(({key: 9}, key, 3), {}, 9)]
    elif name == "rotate_left":
        values = [rng.randint(0, 9) for _ in range(rng.randint(3, 6))]
        k = rng.randint(len(values) + 1, len(values) + 8)
        visible = [((values, 1), {}, values[1:] + values[:1])]
        hidden = [((values, k), {}, values[k % len(values):] + values[: k % len(values)])]
    elif name == "median":
        values = [rng.randint(-10, 10) for _ in range(5)]
        ordered = sorted(values)
        even = sorted([rng.randint(-10, 10) for _ in range(4)])
        visible = [((values,), {}, ordered[len(ordered) // 2])]
        hidden = [((even,), {}, (even[1] + even[2]) / 2)]
    elif name == "is_palindrome":
        visible = [(("Never odd or even",), {}, True)]
        hidden = [(("not a palindrome",), {}, False)]
    return visible, hidden


def _generate_code_tasks(count: int, seed: int) -> List[Task]:
    rng = random.Random(seed)
    tasks: List[Task] = []
    for index in range(count):
        template = _CODE_TASK_TEMPLATES[index % len(_CODE_TASK_TEMPLATES)]
        candidates = list(template["candidates"])
        correct_expression = candidates[0]
        rng.shuffle(candidates)
        correct_index = candidates.index(correct_expression)
        visible, hidden = _variant_cases(str(template["name"]), index, template["visible"], template["hidden"])
        prompt = (
            f"{template['prompt']} Visible tests: {visible}. "
            "Return one complete Python function implementation."
        )
        task = Task(
                task_id=f"code-{index:04d}-{template['name']}",
                prompt=prompt,
                candidates=candidates,
                visible_cases=[],
                hidden_cases=[],
                target_description=str(template["target"]),
                correct_index=correct_index,
                domain="code",
                metadata={
                    "function": template["name"],
                    "visible_tests": visible,
                    "hidden_tests": hidden,
                },
            )
        # Reject a rare variant where a distractor happens to satisfy every
        # test; this keeps the code-repair reward unambiguous at scale.
        passing = []
        for candidate_index, candidate in enumerate(task.candidates):
            try:
                if _run_code_tests(task, candidate, visible) and _run_code_tests(task, candidate, hidden):
                    passing.append(candidate_index)
            except Exception:
                pass
        if len(passing) != 1:
            template_visible, template_hidden = template["visible"], template["hidden"]
            task = Task(
                task_id=task.task_id,
                prompt=task.prompt,
                candidates=task.candidates,
                visible_cases=[],
                hidden_cases=[],
                target_description=task.target_description,
                correct_index=correct_index,
                domain="code",
                metadata={"function": template["name"], "visible_tests": template_visible, "hidden_tests": template_hidden},
            )
        tasks.append(task)
    return tasks


def generate_tasks(count: int, seed: int, domain: str = "arithmetic") -> List[Task]:
    if domain == "code":
        return _generate_code_tasks(count, seed)
    if domain != "arithmetic":
        raise ValueError(f"unknown task domain: {domain}")
    rng = random.Random(seed)
    tasks: List[Task] = []
    for i in range(count):
        a = rng.choice([-3, -2, -1, 1, 2, 3])
        b = rng.randint(-5, 5)
        c = rng.choice([-2, -1, 1, 2])
        d = b + rng.choice([-2, 2, 3])
        visible_x = sorted(rng.sample([-4, -3, -2, -1, 0, 1, 2, 3, 4], 2))
        hidden_pool = [x for x in range(-6, 7) if x not in visible_x]
        hidden_x = sorted(rng.sample(hidden_pool, 4))
        target = lambda x, aa=a, bb=b: aa * x + bb
        visible = [(x, target(x)) for x in visible_x]
        hidden = [(x, target(x)) for x in hidden_x]
        candidates = _candidate_bank(a, b, c, d, visible_x)
        # Candidate order is randomized so a policy must read the task and
        # candidate text instead of learning that action zero is always right.
        correct_expression = candidates[0]
        rng.shuffle(candidates)
        correct_index = candidates.index(correct_expression)
        prompt = (
            "Infer the arithmetic function from the visible examples. "
            f"Visible examples: {visible}. Return one candidate expression in x."
        )
        tasks.append(
            Task(
                task_id=f"task-{i:04d}",
                prompt=prompt,
                candidates=candidates,
                visible_cases=visible,
                hidden_cases=hidden,
                target_description=f"f(x)={a}*x+{b}",
                correct_index=correct_index,
            )
        )
    return tasks


def task_features(task: Task, candidate_index: int) -> List[float]:
    """Small contextual feature vector used by the CPU policy simulator."""
    candidate = task.candidates[candidate_index]
    stable_id = sum((index + 1) * ord(char) for index, char in enumerate(task.task_id)) % 17
    return [
        1.0,
        float(candidate_index == 0),
        float("*x*x" in candidate),
        float("+" in candidate),
        float("-" in candidate),
        float(len(task.visible_cases)),
        float(stable_id) / 17.0,
    ]
